package com.blockproxy.android.cdn

enum class CdnProvider(val storageValue: String, val displayName: String) {
    NONE("none", "关闭"),
    CLOUDFLARE("cloudflare", "Cloudflare"),
    ALIYUN("aliyun", "Aliyun");

    val enabled: Boolean get() = this != NONE

    companion object {
        fun fromStorage(value: String?): CdnProvider {
            return entries.firstOrNull { it.storageValue == value } ?: NONE
        }
    }
}

